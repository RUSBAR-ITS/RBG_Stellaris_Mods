import { test, expect } from '@playwright/test';
import { sttvEnglish, sttvReady, sttvOffset, en, ru } from './helpers';

test('manual opening, language, theme, collapse, and refresh defaults', async ({ page }) => {
  const requests: string[] = [];
  page.on('request', request => requests.push(request.url()));
  await page.goto('/');
  await expect(page.locator('[data-technology-id]')).toHaveCount(0);
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'night');
  await sttvEnglish(page);
  await sttvReady(page);
  await page.getByRole('button', { name: en.sttv_day_theme, exact: true }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'day');
  await page.getByRole('button', { name: en.sttv_collapse_menu, exact: true }).click();
  await expect(page.getByRole('button', { name: en.sttv_language, exact: true })).toHaveCount(0);
  await expect(page.getByRole('complementary')).toHaveCSS('width', '53px');
  await page.getByRole('button', { name: en.sttv_expand_menu, exact: true }).click();
  await expect(page.getByRole('button', { name: en.sttv_language, exact: true })).toBeVisible();
  requests.length = 0;
  await page.reload();
  await expect(page.locator('[data-technology-id]')).toHaveCount(0);
  await expect(page.locator('html')).toHaveAttribute('lang', 'ru');
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'night');
  expect(requests.every(url => new URL(url).origin === new URL(page.url()).origin)).toBe(true);
  expect(requests.some(url => /database\.json|\/api\//.test(url))).toBe(false);
});
test('card tooltip uses the prepared representation without manual variant controls', async ({ page }) => {
  await page.goto('/'); await sttvEnglish(page); await sttvReady(page);
  const card = page.locator('[data-technology-id="tech_example"]');
  await card.click();
  await expect(page.getByRole('tooltip')).toContainText('tech_example details');
  await expect(page.getByRole('tooltip')).toContainText('tech_example');
  const before = await sttvOffset(page);
  await card.click();
  await expect(page.getByRole('option')).toHaveCount(0);
  await expect(card.locator('button')).toHaveCount(0);
  await expect(card).toBeFocused();
  expect(await sttvOffset(page)).toEqual(before);
  await page.getByRole('button', { name: en.sttv_language, exact: true }).click();
  await page.getByRole('option', { name: ru.sttv_language_ru, exact: true }).click();
  await expect(page.locator('[data-area="physics"] [data-technology-id="tech_example"]')).toHaveCount(1);
  await expect(page.getByRole('option')).toHaveCount(0);
});
test('scrollbars support keyboard, wheel, drag and preserve offsets on menu resize', async ({ page }) => {
  const errors: string[] = [];
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.setViewportSize({ width: 1000, height: 700 });
  await page.goto('/'); await sttvEnglish(page); await sttvReady(page);
  const bar = page.locator('[role=scrollbar][aria-orientation=vertical]');
  await bar.focus(); await page.keyboard.press('End');
  expect((await sttvOffset(page)).y).toBeGreaterThan(300);
  await page.keyboard.press('Home'); expect((await sttvOffset(page)).y).toBe(0);
  await page.locator('#sttv-viewport-content').hover();
  await page.mouse.wheel(0, 200); await expect.poll(async () => (await sttvOffset(page)).y).toBeGreaterThan(0);
  const y = (await sttvOffset(page)).y;
  await page.keyboard.down('Shift'); await page.mouse.wheel(0, 100); await page.keyboard.up('Shift');
  await expect.poll(async () => (await sttvOffset(page)).x).toBeGreaterThan(0);
  expect((await sttvOffset(page)).y).toBe(y);
  const before = await sttvOffset(page);
  await page.getByRole('button', { name: en.sttv_collapse_menu, exact: true }).click();
  expect(await sttvOffset(page)).toEqual(before);
  const thumb = bar.locator('.sttv-scrollbar-thumb');
  const box = (await thumb.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down(); await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 + 80); await page.mouse.up();
  await expect.poll(async () => (await sttvOffset(page)).y).toBeGreaterThan(before.y);
  expect(errors).toEqual([]);
});
