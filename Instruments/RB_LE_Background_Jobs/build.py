rules = {}


def helper(name, test):
    key = "rb_le_" + name
    if key in rules:
        assert rules[key] == test
    rules[key] = test
    return key + " = yes"


def district_capacity(district):
    info = objects[district]
    return all_of(test_blocks(info, ("potential", "allow")), tech_gate(info, "owner"),
                  "free_district_slots > 0", f"num_free_districts = {{ type = {district} value > 0 }}")


@cache
def zone_capacity(zone):
    info = objects[zone]
    zone_sets = tokens(info, "zone_sets")
    alternatives = []
    for slot in sorted(domains["zone_slots"]):
        s = objects[slot]
        includes = tokens(s, "include") | {v.strip('"') for v in s["start"]}
        if not (includes & {"all", zone} or tokens(s, "included_zone_sets") & zone_sets):
            continue
        if {zone, "all"} & tokens(s, "exclude") or tokens(s, "excluded_zone_sets") & zone_sets:
            continue
        districts = sorted(d for d in domains["districts"] if slot in tokens(objects[d], "zone_slots"))
        if districts:
            host = any_of(any_of((f"has_district = {d}", helper("can_build_" + d, district_capacity(d)))) for d in districts)
            alternatives.append(all_of(test_blocks(s, ("potential", "unlock")), host))
    # A slot may be respecialized. Automatic starting zones have fixed slots.
    return all_of(test_blocks(info, ("potential", "unlock")),
                  cap_gate(zone, info, "planet_limit", "owner", "num_zones"),
                  cap_gate(zone, info, "empire_limit", "owner", "num_zones"), any_of(alternatives))


def zone_permits(zone, building, building_sets):
    def included(v):
        return bool({building, "all"} & tokens(v, "included_buildings") or building_sets & tokens(v, "included_building_sets"))

    def excluded(v):
        return bool({building, "all"} & tokens(v, "excluded_buildings") or building_sets & tokens(v, "excluded_building_sets"))

    allow = [YES] if included(zone) else []
    deny = [YES] if excluded(zone) else []
    for conditional in zone["triggered_buildings"]:
        extra = defaultdict(list)
        for k, v in fields(expand(parse(contents(conditional)), {}), read_fields | {"trigger"}):
            extra[k].append(v)
        test = test_blocks(extra, ("trigger",))
        if included(extra):
            allow.append(test)
        if excluded(extra):
            deny.append(test)
    if not allow or YES in deny:
        return NO
    return all_of(any_of(allow), group("NOT", any_of(deny)) if deny else YES)


@cache
def building_site(building):
    sets = tokens(objects[building], "building_sets")
    by_gate = defaultdict(list)
    for z in sorted(domains["zones"]):
        gate = zone_permits(objects[z], building, sets)
        if gate != NO:
            by_gate[gate].append(f"has_zone = {{ zone = {z} }}")
    expression = any_of(all_of(g, any_of(zones)) for g, zones in by_gate.items())
    if expression == NO:
        return NO
    # Many buildings share precisely the same permitted zones. Name that list once.
    key = site_names.setdefault(expression, "building_zones_for_" + building)
    return helper(key, expression)


def cap_gate(obj, info, key, empire, counter="num_buildings"):
    if key not in info:
        return YES
    raw = info[key][0]
    kind = info["owner_type"]
    owner_type = f"owner_type = {kind[0]} " if kind else ""
    count = f"{counter} = {{ {owner_type}type = {obj} value < LIMIT }}"
    if re.fullmatch(r"\{ base = \d+ \}", raw):
        raw = contents(raw).split()[-1]
    if raw.startswith("{"):
        name = "rb_le_cap_" + key + "_" + obj
        cap_values[name] = raw
        test = any_of([f"check_variable_arithmetic = {{ which = value:{name} value < 0 }}",
                       count.replace("LIMIT", "value:" + name)])
    else:
        test = count.replace("LIMIT", raw)
    return group(empire, test) if key == "empire_limit" else test


cap_values = {}
site_names = {}


@cache
def building_capacity(obj):
    info = objects[obj]
    kind = next(iter(info["owner_type"]), "")
    empire = {"subject_holding": "owner.overlord", "corporate": "branch_office_owner"}.get(kind, "owner")
    employer = YES
    if kind == "subject_holding":
        employer = "exists = owner.overlord"
        site = "owner = { check_variable_arithmetic = { which = value:rb_le_subject_holding_limit value > 0 } check_variable_arithmetic = { which = value:rb_le_free_subject_holdings value > 0 } }"
    elif kind == "corporate":
        employer = "has_branch_office = yes"
        site = "free_branch_office_building_slots > 0"
    else:
        site = all_of("free_building_slots > 0", building_site(obj)) if info["can_build"] != ["no"] else NO
    upgrades = [any_of((f"has_active_building = {parent}", building_capacity(parent)))
                for parent in sorted(parents[obj])]
    site = any_of([site, *upgrades])
    if site == NO:
        return NO
    gates = test_blocks(info, ("potential", "allow"))
    if obj == "building_medical_2":
        gates = gates.replace("root = {", "prev = {")
    if obj == "building_ai_emporium":
        gates = gates.replace("root.branch_office_owner", "prevprev.branch_office_owner")
    # A holding's vanilla building context uses planet.owner to reach its host.
    gates = gates.replace("planet.owner", "owner")
    return all_of(employer, tech_gate(info, empire), gates, cap_gate(obj, info, "planet_limit", empire),
                  cap_gate(obj, info, "empire_limit", empire), site)


def starbase_capacity(obj, domain):
    info = objects[obj]
    slot_key = "module_slots" if domain == "starbase_modules" else "building_slots"
    fits = tokens(info, "fits_on_slots")
    excluded = tokens(info, "cannot_fit_on_slots")
    sizes = defaultdict(list)
    base_type, = info["starbase_type"]
    assert base_type in {"arkship", "orbital_ring"}, obj
    kind = slot_key.removesuffix("_slots")
    for level in sorted(domains["starbase_levels"]):
        if base_type not in level:
            continue
        slots = tokens(objects[level], slot_key)
        permitted = (slots & fits if fits else slots) - excluded
        if not permitted:
            continue
        outside = slots - permitted
        # The capital shipyard needs the spinal mount. Ordinary modules exclude it.
        spinal_only = permitted == {"spinal_mount_1"}
        assert not outside or spinal_only or outside == {"spinal_mount_1"}, (obj, outside)
        cells = len(slots) if spinal_only else len(permitted)
        capacity = f"rb_le_{kind}_slots_{cells}" + ("_regular" if outside and not spinal_only else "")
        raw = f"base = {cells} add = modifier:starbase_{kind}_capacity_add"
        spinal_check = YES
        if outside:
            spinal_types = sorted(m for m in domains[domain] if tokens(objects[m], "fits_on_slots") == {"spinal_mount_1"})
            if spinal_only:
                value = "rb_le_available_spinal_mounts"
                used = [group("complex_trigger_modifier", f"trigger = count_starbase_modules parameters = {{ type = {m} }} mode = add mult = -1")
                        for m in spinal_types]
                cap_values[value] = "{ base = 1 add = modifier:starbase_module_capacity_add " + " ".join(used) + " }"
                spinal_check = f"check_variable_arithmetic = {{ which = value:{value} value > 0 }}"
            else:
                raw += " " + group("modifier", "add = 1 " + any_of(f"has_starbase_module = {m}" for m in spinal_types))
        cap_values[capacity] = "{ " + raw + " }"
        sizes[capacity, spinal_check].append("has_starbase_size = " + objects[level]["ship_size"][0])
    space = any_of(all_of(any_of(levels), f"count_{domain} = {{ count < value:{cap} }}", spinal_check)
                   for (cap, spinal_check), levels in sizes.items())
    limits = []
    for key, default in (("starbase_limit", 1 if kind == "building" else -1), ("empire_limit", -1)):
        raw = info.get(key, [f"{{ base = {default} }}"])[0]
        number = re.fullmatch(r"\{ base = (-?\d+) \}", raw)
        if number and int(number[1]) < 0:
            continue
        if number:
            test = f"count_{domain} = {{ type = {obj} count < {number[1]} }}"
        else:
            cap = f"rb_le_{key}_{obj}"
            cap_values[cap] = raw
            test = any_of((f"check_variable_arithmetic = {{ which = value:{cap} value < 0 }}",
                           f"count_{domain} = {{ type = {obj} count < value:{cap} }}"))
        limits.append(group("owner", test) if key == "empire_limit" else test)
    room = helper(site_names.setdefault(space, "space_for_" + obj), space) if space != NO else NO
    return all_of(room, *limits, test_blocks(info, ("potential", "possible", "allow")), tech_gate(info, "owner"))


def grant_test(row):
    # The registry has already expanded vanilla inline parameters and preserves each multiplier.
    text = row["Grant branch and conditions"].split(" / ")[0]
    _, _, operands = text.partition(" ")
    info = defaultdict(list)
    for key, value in fields(expand(parse(operands), {}), {"potential", "mult"}):
        info[key].append(value)
    gates = test_blocks(info, ("potential",)).replace("planet.owner", "owner")
    positive = [f"check_variable_arithmetic = {{ which = {mult} value > 0 }}"
                for mult in info["mult"] if not re.fullmatch(r"\d+(\.\d+)?", mult)]
    return all_of(gates, *positive)


@cache
def can_create_source(obj, domain):
    if domain == "zones":
        test = zone_capacity(obj)
    elif domain == "districts":
        test = district_capacity(obj)
    elif domain == "buildings":
        test = building_capacity(obj)
    else:
        test = starbase_capacity(obj, domain)
    return helper("can_build_" + obj, test) if test != NO else NO


def future_sources(job):
    groups = defaultdict(list)
    for obj, branches in sorted(grants[job].items()):
        domain = branches[0]["Provider type"]
        source = can_create_source(obj, domain)
        if source == NO:
            continue
        grant = any_of(grant_test(row) for row in branches)
        # Vanilla evaluates the grant on an existing building; the catalogue also visits colonies without one.
        if "corporate" in objects[obj]["owner_type"] and "branch_office_owner" in grant:
            grant = all_of("has_branch_office = yes", grant)
        base = objects[obj]["starbase_type"][0] if domain.startswith("starbase_") else ""
        groups[base, grant].append(source)
    prospective = []
    for (base, grant), sources in groups.items():
        test = all_of(grant, any_of(sources))
        if base == "arkship":
            test = all_of("is_planet_class = pc_ark", "exists = starbase", group("starbase", test))
        elif base == "orbital_ring":
            test = all_of("exists = orbital_defence.starbase", group("orbital_defence.starbase", test))
        prospective.append(test)
    return any_of(prospective)


def domestic_script(row):
    s = row["Domestic scripted route"]
    if not s:
        return NO
    if "POOL(commander)" in s:
        # Army Veteran and Retired Fleet Officer admit pool officials and scientists in every empire.
        return YES
    if "POOL(" in s:
        return "OR = { is_gestalt = no AND = { has_paragon_dlc = yes is_crisis_faction = no } }"
    if row["ID"] == "noble":
        return "OR = { has_valid_civic = civic_aristocratic_elite is_imperial_authority = yes }"
    assert row["ID"] in {"angler", "farmer"}
    anglers = "yes" if row["ID"] == "angler" else "no"
    return f"AND = {{ country_uses_food = yes is_crisis_faction = no is_wilderness_empire = no is_anglers_empire = {anglers} }}"


job_rules = {}
for job, row in catalog.items():
    route = row["Route"]
    worker = f"any_owned_pop_group = {{ can_work_specific_job = {job} }}"
    sources = []
    if route == "Uncapped job":
        if job == "squire":
            sources.append("OR = { has_active_building = building_order_keep has_active_building = building_order_castle }")
        else:
            sources.append(YES)
    elif route != "Scripted only":
        # Use the engine's final current capacity, including deprioritized and occupied places.
        sources.extend([f"num_assigned_jobs = {{ job = {job} value > 0 }}",
                        f"free_jobs_of_type = {{ job = {job} include_deprioritized_jobs = yes value > 0 }}",
                        future_sources(job)])
        if job in location_gates:
            presence = "has_deposit" if route == "Colony feature" else "has_modifier"
            locations = [all_of(f"{presence} = {r['Provider ID']}", grant_test(r)) for r in location_gates[job]]
            sources = [all_of(any_of(locations), any_of(sources))]
    domestic = domestic_script(row)
    economic = group("any_owned_colony", all_of(any_of(sources), worker)) if sources else NO
    job_rules[job] = any_of((domestic, economic))


def readable(test):
    # Format nested compound triggers once, without splitting a quoted string or an inline argument.
    words = re.findall(r'"[^"]*"|[^\s{}]+|[{}]', test)
    lines, line, depth = [], [], 1
    for i, word in enumerate(words):
        if word == "}":
            if line:
                lines.append("\t" * depth + " ".join(line))
                line = []
            depth -= 1
            lines.append("\t" * depth + "}")
        else:
            line.append(word)
            if word == "{" or (i >= 1 and words[i - 1] in {"=", ">=", ">", "<=", "<", "!=", "?="}):
                lines.append("\t" * depth + " ".join(line))
                line = []
                if word == "{":
                    depth += 1
    if line:
        lines.append("\t" * depth + " ".join(line))
    return "\n".join(lines)


def trigger_file(dictionary):
    return "\n\n".join(f"{k} = {{\n{readable(v)}\n}}" for k, v in sorted(dictionary.items())) + "\n"


