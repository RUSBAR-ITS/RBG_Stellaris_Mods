def read_table(name):
    with (REPO / f"docs/RB_LE/{name}_4_6_0_EN.csv").open(encoding="utf-8-sig", newline="") as stream:
        return list(csv.DictReader(stream, delimiter=";"))


def parse(text):
    return Parser(Source(text), syntax, specials=False).sequence()[0]


@cache
def file_nodes(path):
    return parse(path.read_text(encoding="utf-8-sig"))


def substitute(text, params):
    return re.sub(r"\$(\w+)\$", lambda m: params.get(m[1], m[0]), text)


def expand(nodes, params):
    for node in nodes:
        if isinstance(node, Conditional):
            if (node.parameter in params) != node.negated:
                yield from expand(node.items, params)
        elif isinstance(node, Assignment) and node.key.text == "inline_script":
            if isinstance(node.value, Block):
                child = {n.key.text: substitute(n.value.text, params) for n in node.value.items
                         if isinstance(n, Assignment) and isinstance(n.value, Scalar)}
                name = child.pop("script")
            else:
                name, child = substitute(node.value.text, params), {}
            yield from expand(file_nodes(common / "inline_scripts" / (name + ".txt")), child)
        else:
            yield node, params


def render(node, params):
    if isinstance(node, Block):
        return "{ " + " ".join(render(n, p) for n, p in expand(node.items, params)) + " }"
    if isinstance(node, Assignment):
        return f"{substitute(node.key.raw, params)} {node.operator} {render(node.value, params)}"
    return substitute(node.raw, params)


def fields(nodes, names):
    return [(node.key.text, render(node.value, env)) for node, env in nodes
            if isinstance(node, Assignment) and node.key.text in names]


def contents(value):
    assert value.startswith("{") and value.endswith("}"), value
    return value[1:-1].strip()


def tokens(values, key):
    return {v.strip('"') for group in values.get(key, []) for v in contents(group).split()}


def group(key, body):
    return f"{key} = {{ {body} }}"


YES, NO = "always = yes", "always = no"


def junction(kind, values):
    identity, stop = (YES, NO) if kind == "AND" else (NO, YES)
    parts = list(dict.fromkeys(v for v in values if v and v != identity))
    if stop in parts:
        return stop
    if not parts:
        return identity
    if len(parts) == 1:
        return parts[0]
    return group(kind, " ".join(parts))


def all_of(*args):
    return junction("AND", args)


def any_of(args):
    return junction("OR", args)


def test_blocks(values, keys):
    # Preserve each complete vanilla AND block when combining alternatives.
    return all_of(*(group("AND", contents(b)) for k in keys for b in values.get(k, []) if contents(b)))


def tech_gate(values, empire):
    techs = sorted(tokens(values, "prerequisites"))
    return group(empire, " ".join(f"has_technology = {t}" for t in techs)) if techs else YES


def write(path, content):
    path = mod / path
    content = "# Generated by Instruments/RB_LE_Background_Jobs/build.py for Stellaris 4.6.0.\n" + content
    if args.check:
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            raise ValueError(f"Regenerate {path}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")


def definition(name, lines):
    return f"{name} = {{\n" + "\n".join("\t" + line for line in lines) + "\n}\n"


